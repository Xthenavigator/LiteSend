#!/usr/bin/env python3
"""Reference LocalSend protocol v2 peer (test harness, not part of the app).

Implements just enough of the official protocol to validate the Android client:

  python peer.py serve  --port 53317 --dir received
  python peer.py send   --ip 192.168.0.197 --file some.bin
  python peer.py text   --ip 192.168.0.197 --message "hello"
  python peer.py watch

TLS uses the certificate/key files generated by tools/CertGen.java
(cert.pem / key.pem), so the wire format matches what LocalSend peers see.
"""

import argparse
import http.client
import http.server
import json
import os
import socket
import ssl
import struct
import sys
import threading
import time
import uuid

PROTOCOL_VERSION = "2.0"
MULTICAST_GROUP = "224.0.0.167"
DEFAULT_PORT = 53317

MIME = {
    ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".gif": "image/gif",
    ".mp4": "video/mp4", ".mp3": "audio/mpeg", ".pdf": "application/pdf",
    ".txt": "text/plain", ".apk": "application/vnd.android.package-archive",
    ".zip": "application/zip", ".json": "application/json",
}


def mime_of(name):
    _, ext = os.path.splitext(name.lower())
    return MIME.get(ext, "application/octet-stream")


class State(object):
    def __init__(self):
        self.port = DEFAULT_PORT
        self.https = True
        self.alias = "python-peer"
        self.model = "python"
        self.fingerprint = "0" * 64
        self.dir = "received"
        self.session = None
        self.files = {}


STATE = State()


class Handler(http.server.BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):
        sys.stderr.write("PEER %s\n" % (fmt % args))

    def _json(self, code, obj):
        body = json.dumps(obj).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _error(self, code, message):
        self._json(code, {"message": message})

    def _info(self):
        return {
            "alias": STATE.alias,
            "version": PROTOCOL_VERSION,
            "deviceModel": STATE.model,
            "deviceType": "desktop",
            "fingerprint": STATE.fingerprint,
            "download": False,
        }

    def _body(self):
        length = int(self.headers.get("Content-Length", "0") or 0)
        return self.rfile.read(length) if length > 0 else b""

    def do_GET(self):
        path = self.path.split("?")[0]
        if path in ("/api/localsend/v1/info", "/api/localsend/v2/info"):
            self._json(200, self._info())
        else:
            self._error(404, "Not found")

    def do_POST(self):
        path, _, query = self.path.partition("?")
        params = {}
        for pair in query.split("&"):
            if "=" in pair:
                k, v = pair.split("=", 1)
                params[k] = v

        if path in ("/api/localsend/v1/info", "/api/localsend/v1/register",
                    "/api/localsend/v2/register"):
            body = self._body()
            try:
                data = json.loads(body.decode("utf-8")) if body else {}
            except ValueError:
                return self._error(400, "Request body malformed")
            print("REGISTER from %s alias=%s" % (self.client_address[0], data.get("alias")))
            return self._json(200, self._info())

        if path in ("/api/localsend/v1/send-request", "/api/localsend/v2/prepare-upload"):
            body = self._body()
            try:
                data = json.loads(body.decode("utf-8"))
            except ValueError:
                return self._error(400, "Request body malformed")
            files = data.get("files") or {}
            if not files:
                return self._error(400, "Request must contain at least one file")

            # Single text file with preview == text message: read and close.
            if len(files) == 1:
                only = list(files.values())[0]
                if only.get("preview") and str(only.get("fileType", "")).startswith("text"):
                    print("MESSAGE from %s: %s" % (data.get("info", {}).get("alias"), only["preview"]))
                    return self._json(204, {})

            session_id = str(uuid.uuid4())
            tokens = {}
            STATE.session = session_id
            STATE.files = {}
            os.makedirs(STATE.dir, exist_ok=True)
            for file_id, f in files.items():
                token = str(uuid.uuid4())
                tokens[file_id] = token
                STATE.files[file_id] = {"token": token, "fileName": f.get("fileName", "file"),
                                        "size": f.get("size", 0)}
            print("PREPARE %d file(s) session=%s" % (len(tokens), session_id))
            if "v2" in path:
                return self._json(200, {"sessionId": session_id, "files": tokens})
            return self._json(200, tokens)

        if path in ("/api/localsend/v1/send", "/api/localsend/v2/send", "/api/localsend/v2/upload"):
            file_id = params.get("fileId")
            token = params.get("token")
            entry = STATE.files.get(file_id)
            if not entry or entry["token"] != token:
                return self._error(403, "Invalid token")
            length = int(self.headers.get("Content-Length", "0") or 0)
            name = os.path.basename(entry["fileName"])
            target = os.path.join(STATE.dir, name)
            base, ext = os.path.splitext(target)
            counter = 1
            while os.path.exists(target):
                target = "%s(%d)%s" % (base, counter, ext)
                counter += 1
            received = 0
            with open(target, "wb") as out:
                remaining = length
                while remaining > 0:
                    chunk = self.rfile.read(min(65536, remaining))
                    if not chunk:
                        break
                    out.write(chunk)
                    received += len(chunk)
                    remaining -= len(chunk)
            print("SAVED %s (%d/%d bytes)" % (target, received, length))
            del STATE.files[file_id]
            return self._json(200, {})

        if path in ("/api/localsend/v1/cancel", "/api/localsend/v2/cancel"):
            STATE.session = None
            STATE.files = {}
            self._body()
            return self._json(200, {})

        if path in ("/api/localsend/v1/show", "/api/localsend/v2/show"):
            self._body()
            return self._json(403, "Invalid token")

        self._error(404, "Not found")


def serve(args):
    STATE.port = args.port
    STATE.alias = args.alias
    STATE.dir = args.dir
    os.makedirs(STATE.dir, exist_ok=True)

    server = http.server.ThreadingHTTPServer(("0.0.0.0", args.port), Handler)
    if args.https:
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.load_cert_chain(os.path.join(args.certdir, "cert.pem"),
                                os.path.join(args.certdir, "key.pem"))
        server.socket = context.wrap_socket(server.socket, server_side=True)
    print("SERVING %s on port %d (https=%s), saving to %s"
          % (STATE.alias, args.port, args.https, STATE.dir), flush=True)

    if not args.no_multicast:
        thread = threading.Thread(target=announce_loop, args=(args.port, args.https))
        thread.daemon = True
        thread.start()

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


def announce_loop(port, https):
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    sock.setsockopt(socket.IPPROTO_IP, socket.IP_MULTICAST_TTL, 2)
    payload = json.dumps({
        "alias": STATE.alias,
        "version": PROTOCOL_VERSION,
        "deviceModel": STATE.model,
        "deviceType": "desktop",
        "fingerprint": STATE.fingerprint,
        "port": port,
        "protocol": "https" if https else "http",
        "download": False,
        "announce": True,
        "announcement": True,
    }).encode("utf-8")
    while True:
        try:
            sock.sendto(payload, (MULTICAST_GROUP, DEFAULT_PORT))
        except Exception as e:
            print("multicast send failed: %r" % (e,))
        time.sleep(3)


def watch(args):
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    sock.bind(("", DEFAULT_PORT))
    mreq = struct.pack("4s4s", socket.inet_aton(MULTICAST_GROUP), socket.inet_aton("0.0.0.0"))
    sock.setsockopt(socket.IPPROTO_IP, socket.IP_ADD_MEMBERSHIP, mreq)
    print("WATCHING multicast %s:%d" % (MULTICAST_GROUP, DEFAULT_PORT), flush=True)
    while True:
        data, addr = sock.recvfrom(8192)
        try:
            dto = json.loads(data.decode("utf-8"))
        except ValueError:
            continue
        print("ANNOUNCE %s alias=%s port=%s protocol=%s announce=%s"
              % (addr[0], dto.get("alias"), dto.get("port"), dto.get("protocol"), dto.get("announce")),
              flush=True)


def client_connection(ip, port):
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    context.check_hostname = False
    context.verify_mode = ssl.CERT_NONE
    return http.client.HTTPSConnection(ip, port, timeout=30, context=context)


def request(ip, port, method, path, body=None, headers=None):
    conn = client_connection(ip, port)
    try:
        conn.request(method, path, body=body, headers=headers or {})
        response = conn.getresponse()
        data = response.read()
        return response.status, data
    finally:
        conn.close()


def resolve(ip, port):
    status, data = request(ip, port, "GET", "/api/localsend/v1/info?fingerprint=" + "f" * 64)
    if status != 200:
        raise RuntimeError("info failed: %s %r" % (status, data))
    dto = json.loads(data.decode("utf-8"))
    dto["version"] = dto.get("version") or "1.0"
    return dto


def send(args):
    target = resolve(args.ip, args.port)
    print("TARGET %s (%s, v%s)" % (target.get("alias"), args.ip, target.get("version")))
    legacy = target.get("version") == "1.0"

    file_id = str(uuid.uuid4())
    name = os.path.basename(args.file)
    size = os.path.getsize(args.file)
    file_dto = {
        "id": file_id,
        "fileName": name,
        "size": size,
        "fileType": mime_of(name),
        "metadata": {"modified": time.strftime("%Y-%m-%dT%H:%M:%S.000Z", time.gmtime())},
    }
    if legacy:
        mime = mime_of(name)
        file_dto["fileType"] = ("image" if mime.startswith("image/") else
                                "video" if mime.startswith("video/") else
                                "pdf" if mime == "application/pdf" else
                                "text" if mime.startswith("text/") else "other")

    payload = json.dumps({
        "info": {
            "alias": "python-peer",
            "version": PROTOCOL_VERSION,
            "deviceModel": STATE.model,
            "deviceType": "desktop",
            "fingerprint": STATE.fingerprint,
            "port": args.port,
            "protocol": "https",
            "download": False,
        },
        "files": {file_id: file_dto},
    }).encode("utf-8")

    path = "/api/localsend/v1/send-request" if legacy else "/api/localsend/v2/prepare-upload"
    status, data = request(args.ip, args.port, "POST", path, payload,
                           {"Content-Type": "application/json"})
    print("PREPARE %s %r" % (status, data[:300]))
    if status != 200:
        raise RuntimeError("prepare-upload failed")
    response = json.loads(data.decode("utf-8"))
    if legacy:
        token = response.get(file_id)
        session_id = None
    else:
        session_id = response.get("sessionId")
        token = (response.get("files") or {}).get(file_id)
    if not token:
        print("Receiver accepted nothing")
        return

    upload_path = "/api/localsend/v1/send" if legacy else "/api/localsend/v2/upload"
    query = "?fileId=%s&token=%s" % (file_id, token)
    if session_id:
        query = "?sessionId=%s&fileId=%s&token=%s" % (session_id, file_id, token)

    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    context.check_hostname = False
    context.verify_mode = ssl.CERT_NONE
    conn = http.client.HTTPSConnection(args.ip, args.port, timeout=300, context=context)
    try:
        with open(args.file, "rb") as f:
            conn.putrequest("POST", upload_path + query)
            conn.putheader("Content-Type", mime_of(name))
            conn.putheader("Content-Length", str(size))
            conn.endheaders()
            sent = 0
            while True:
                chunk = f.read(65536)
                if not chunk:
                    break
                conn.send(chunk)
                sent += len(chunk)
                if sent % (8 * 1024 * 1024) < 65536:
                    print("UPLOAD %d/%d" % (sent, size))
        response = conn.getresponse()
        body = response.read()
        print("UPLOAD RESULT %s %r" % (response.status, body[:200]))
    finally:
        conn.close()


def send_text(args):
    target = resolve(args.ip, args.port)
    print("TARGET %s" % target.get("alias"))
    file_id = str(uuid.uuid4())
    content = args.message.encode("utf-8")
    payload = json.dumps({
        "info": {
            "alias": "python-peer",
            "version": PROTOCOL_VERSION,
            "deviceModel": STATE.model,
            "deviceType": "desktop",
            "fingerprint": STATE.fingerprint,
            "port": args.port,
            "protocol": "https",
            "download": False,
        },
        "files": {file_id: {
            "id": file_id,
            "fileName": str(uuid.uuid4()) + ".txt",
            "size": len(content),
            "fileType": "text/plain",
            "preview": args.message,
        }},
    }).encode("utf-8")
    status, data = request(args.ip, args.port, "POST", "/api/localsend/v2/prepare-upload",
                           payload, {"Content-Type": "application/json"})
    print("TEXT RESULT %s %r" % (status, data[:300]))


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command")

    p_serve = sub.add_parser("serve")
    p_serve.add_argument("--port", type=int, default=DEFAULT_PORT)
    p_serve.add_argument("--dir", default="received")
    p_serve.add_argument("--alias", default="python-peer")
    p_serve.add_argument("--certdir", default=".")
    p_serve.add_argument("--https", dest="https", action="store_true", default=True)
    p_serve.add_argument("--no-https", dest="https", action="store_false")
    p_serve.add_argument("--no-multicast", action="store_true")

    p_send = sub.add_parser("send")
    p_send.add_argument("--ip", required=True)
    p_send.add_argument("--port", type=int, default=DEFAULT_PORT)
    p_send.add_argument("--file", required=True)

    p_text = sub.add_parser("text")
    p_text.add_argument("--ip", required=True)
    p_text.add_argument("--port", type=int, default=DEFAULT_PORT)
    p_text.add_argument("--message", required=True)

    sub.add_parser("watch")

    args = parser.parse_args()
    if args.command == "serve":
        serve(args)
    elif args.command == "send":
        send(args)
    elif args.command == "text":
        send_text(args)
    elif args.command == "watch":
        watch(args)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
